#!/usr/bin/env python3
"""The Learn blocks: faraday/faraday-learn/src/how.rs (docs/CRYPTO-LEARN.md §3.1).

    gen_how.py --check-screens    the screens check (§9.2): fail when a screen's code
                                  calls an action's root and the screen is missing from
                                  the action's `screens`
    gen_how.py --self-test

`gen.py write` and `gen.py check` call `how_text(root, data)`; everything above the
`// ---- lookups` marker line of how.rs is written here, the lookups below it are kept
as they are. Standard library only (`tomllib`, Python 3.11).

What a block reads, and from where:

    Action, Standards, Limits   the manifest (standards by number, name and status)
    Implementation              the crate, each library with the version `Cargo.lock` has,
                                what the action adds
    Checked against             vectors, tests, self-test checks, the fuzz target or why
                                there is none
    Cross-check                 the area's attributes (tools/crosscheck/facts.py, read
                                without importing the area) and the stamp's seed and the
                                area's case count; written once per area as a static
                                that every block of the area refers to; before it, the
                                action's own `independence` lines (F160): the label of an
                                own construction, and who wrote the reference and
                                whether it is an independent check
    Code                        `code`, split at the first `::` into file and function
    Secret handling, own calls  the manifest

Kinds: `Warn` for what is not checked ("no fuzz target: ...", "not stated by the
library", "no decision", "not cross-checked: ..."), `Mono` for text read character by
character (paths, functions, versions, names of tests and checks), else `Plain`.
"""

import pathlib
import re
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
HOW = "faraday/faraday-learn/src/how.rs"
LOCK = "Cargo.lock"
STAMP = "tools/crosscheck/stamp"
MARKER = "// ---- lookups (the same in every generation) ----"
REPO_ADDRESS = "github.com/bitcoinpasada/faraday"

WHEN = ("Whenever the crypto changes, and with a new seed and about ten times the cases "
        "before every release.")

HEADER = '''//! GENERATED by docs/crypto/gen.py from docs/crypto/actions.toml
//! (`docs/CRYPTO-LEARN.md` §3.1). Do not edit by hand.
//!
//! The shape the generator emits, which the apps read as it is:
//!
//! - one `pub static BLOCKS: &[Block]`, a `Block` per action in the
//!   manifest's order, each one `Block { .. }` literal with every field
//!   of `crate::block::Block` set: `id`, `name`, `action`, `standards`,
//!   `implementation`, `checked`, `cross_check`, `code`, `secret`,
//!   `limits`, `own_calls` (the nine fields of §1, Cross-check as a
//!   `CrossCheck`: `Area` referring to the area's one static, which holds
//!   its parts, seed and case count, or
//!   `Not("not cross-checked: <reason>")`), `independence` (the lines
//!   drawn first in Cross-check, F160: an own construction's label, who
//!   wrote the reference and whether it is an independent check; empty
//!   for neither), then `screens` (the `Screen`
//!   variants' names, or `starter:<page>`) and `learn` (a page id, or
//!   `""` for none);
//! - a `Line` per entry: `Kind::Warn` for what is not checked,
//!   `Kind::Mono` for text read character by character, else
//!   `Kind::Plain`; a library's version read from `Cargo.lock`; no
//!   release string (it is filled when the block is drawn);
//! - an area's text is one `static AREA_<NAME>: Area`, written once and
//!   referred to by every block of the area;
//! - an action with no screen (`screens: &[]`, `learn: ""`) is emitted
//!   too and is offered nowhere;
//! - `CONSTRUCTIONS` (`docs/CRYPTO-LEARN.md` §18), written by gen.py: a
//!   `Construction` per `[[construction]]` in the manifest's order, its
//!   paragraphs' placeholders filled from the code, one about work not
//!   built led by "Planned, not built:", its tables written from the code;
//! - only `BLOCKS`, `learn_page`, `CONSTRUCTIONS` and the area statics change between generations. The
//!   lookups below the marker line are written once and the same in
//!   every generation.

use crate::block::{Area, Block, Code, CrossCheck, Kind, Line};

const fn p(text: &'static str) -> Line {
    Line {
        text,
        kind: Kind::Plain,
    }
}

const fn m(text: &'static str) -> Line {
    Line {
        text,
        kind: Kind::Mono,
    }
}

const fn w(text: &'static str) -> Line {
    Line {
        text,
        kind: Kind::Warn,
    }
}

const fn c(file: &'static str, function: &'static str) -> Code {
    Code { file, function }
}
'''


def as_list(v):
    return v if isinstance(v, list) else ([] if v is None else [v])


# ---------------------------------------------------------------------- reading

def lock_versions(root):
    """{package: [versions]} from Cargo.lock."""
    lock = tomllib.loads((pathlib.Path(root) / LOCK).read_text())
    out = {}
    for pkg in lock.get("package", []):
        out.setdefault(pkg["name"], []).append(pkg["version"])
    return out


def read_stamp(root):
    """(seed, {area: cases}) from the cross-check's stamp."""
    seed, cases = None, {}
    for line in (pathlib.Path(root) / STAMP).read_text().splitlines():
        if line.startswith("seed "):
            seed = line[5:].strip()
        m_ = re.fullmatch(r"cases (\S+) (\d+)", line)
        if m_:
            cases[m_.group(1)] = int(m_.group(2))
    if seed is None:
        raise SystemExit(f"{STAMP}: no seed line")
    return seed, cases


def read_facts(root):
    """({area key: attributes}, {manifest area name: area key}), through
    tools/crosscheck/facts.py, without importing an area. The manifest names an area by
    its file (`area_own.py` is `own`), the cross-check and its stamp by its key
    (`own-randomness`)."""
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(pathlib.Path(root) / "tools" / "crosscheck"))
    try:
        import facts  # noqa: PLC0415
        keys = {module.removeprefix("area_"): key for key, module in facts.areas()}
        return facts.all_facts(), keys
    finally:
        sys.path.pop(0)


# --------------------------------------------------------------------- the text

def rs(s):
    """A Rust string literal."""
    out = ['"']
    for ch in s:
        out.append({'"': '\\"', "\\": "\\\\", "\n": " ", "\t": " "}.get(ch, ch))
    out.append('"')
    return "".join(out)


def line(kind, text):
    return f"{ {'plain': 'p', 'mono': 'm', 'warn': 'w'}[kind] }({rs(text)})"


def lines(items):
    return "&[" + ", ".join(line(k, t) for k, t in items) + "]"


def sentence(s):
    s = " ".join(s.split())
    return s if s.endswith((".", "!", "?")) else s + "."


def prose(s):
    """A fact of an area: no backticks, a capital where the first word is a word, a stop."""
    s = " ".join(s.replace("`", "").split())
    first = s.split(" ")[0] if s else ""
    if first and first[0].islower() and re.fullmatch(r"[a-z]+", first):
        s = s[0].upper() + s[1:]
    return sentence(s)


def standard_lines(data, a):
    out = []
    for k in as_list(a.get("standards")):
        std = data["standard"][k]
        status = std["status"]
        if str(std.get("source", "")).startswith("vendored"):
            status += ", vendored"
        out.append(("plain", f"{k}, {std['name']}, {status}"))
    if not out:
        decisions = [o.get("decision") for o in as_list(a.get("own"))
                     if o.get("decision") and o.get("decision") != "no decision"]
        if decisions:
            out.append(("plain", "None: Faraday's own (" + ", ".join(sorted(set(decisions))) + ")"))
        else:
            out.append(("warn", "None: Faraday's own (no decision)"))
    return out


def implementation_lines(a, versions):
    impl = a["implementation"]
    out = [("mono", impl["crate"])]
    for lib in as_list(impl.get("libraries")):
        have = versions.get(lib)
        if not have:
            raise SystemExit(f"{a['id']}: library {lib} is not in Cargo.lock")
        out.append(("mono", f"{lib} {' and '.join(sorted(set(have)))}"))
    out.append(("plain", sentence(impl["adds"])))
    return out


def checked_lines(a):
    chk = a["checked"]
    out = []
    vectors = as_list(chk.get("vectors"))
    out += [("mono", f"tools/vectors/{v}") for v in vectors]
    if not vectors:
        out.append(("warn", "not checked against vectors"))
    out += [("mono", t) for t in as_list(chk.get("tests"))]
    out += [("mono", f"self-test {t}") for t in as_list(chk.get("selftest"))]
    out += [("mono", f"fuzz {t}") for t in as_list(chk.get("fuzz"))]
    if chk.get("fuzz_none"):
        out.append(("warn", "no fuzz target: " + chk["fuzz_none"].rstrip(".")))
    return out


def secret_lines(a):
    sec = a["secrets"]
    out = []
    reveal = sec["reveal"]
    if reveal == "none":
        out.append(("plain", "none: no secret leaves faraday-keys"))
    else:
        out += [("mono", r) for r in reveal]
    ct = sec["constant_time"]
    out.append(("warn" if ct.lower().startswith("not stated") else "plain", sentence(ct)))
    out.append(("plain", sentence(sec["wiped"])))
    return out


def own_lines(a):
    out = []
    for o in as_list(a.get("own")):
        dec = o.get("decision", "no decision")
        text = sentence(o["text"])
        if dec == "no decision":
            out.append(("plain", f"{text} {o['kind']}."))
            out.append(("warn", "no decision"))
        else:
            out.append(("plain", f"{text} {o['kind']}, {dec}."))
    if not out:
        out.append(("plain", "none"))
    return out


def bare_text(s):
    """Text set inside a sentence: no backticks, one space, a stop, its first letter kept."""
    return sentence(" ".join(s.replace("`", "").split()))


def independence_lines(a):
    """The lines drawn first in the Cross-check field (F160): an own construction's
    label, then who wrote the area's reference and whether it is an independent check."""
    chk = a["checked"]
    out = []
    if a.get("label"):
        out.append(("warn", sentence(a["label"][0].upper() + a["label"][1:])))
    if not chk.get("crosscheck"):
        return out
    by = bare_text(chk["independence"]["author"])
    ind = chk["independence"]["class"]
    if ind == "outside":
        out.append(("plain", "Reference written outside Faraday: " + by))
        return out
    what = "partly Faraday's own" if ind == "own-over-outside" else "Faraday's own model"
    out.append(("warn", f"Not an independent check: the reference is {what}. "
                f"Faraday's part: {bare_text(chk['independence']['ours'])}"))
    out.append(("plain", "Reference written by " + by))
    return out


def code_entries(a):
    out = []
    for f in as_list(a.get("code")):
        file, _, fn = f.partition("::")
        out.append(f"c({rs(file)}, {rs(fn)})")
    return "&[" + ", ".join(out) + "]"


def static_name(area):
    return "AREA_" + re.sub(r"[^A-Za-z0-9]", "_", area).upper()


def area_static(name, key, f, seed, cases):
    if f is None:
        raise SystemExit(f"area {key}: no facts")
    second = [("plain", prose(f["reference"])), ("plain", "Checked first: " + prose(f["reference_checked"]))]
    if f.get("not_compared", "none").strip().lower() != "none":
        second.append(("warn", prose(f["not_compared"])))
    diffs = [d for d in as_list(f.get("differences")) if d.strip().lower() != "none"]
    differences = [("plain", prose(d)) for d in diffs] or [("plain", "None known.")]
    code = [("plain", " ".join(f["faraday"].replace("`", "").split()))]
    return (
        "#[rustfmt::skip]\n"
        f"static {static_name(name)}: Area = Area {{\n"
        f"    area: {rs(key)},\n"
        f"    code: {lines(code)},\n"
        f"    second: {lines(second)},\n"
        f"    vectors: {lines([('plain', prose(f['vectors']))])},\n"
        f"    random: {lines([('plain', prose(f['corpus']))])},\n"
        f"    differences: {lines(differences)},\n"
        f"    when: {lines([('plain', WHEN)])},\n"
        f"    seed: {rs(seed)},\n"
        f"    cases: {cases},\n"
        "};\n"
    )


def block_text(data, a, versions):
    chk = a["checked"]
    if chk.get("crosscheck"):
        cc = f"CrossCheck::Area(&{static_name(chk['crosscheck'])})"
    else:
        cc = f"CrossCheck::Not({rs('not cross-checked: ' + chk['not_crosschecked'].rstrip('.'))})"
    learn = "" if a["learn"] == "none" else a["learn"]
    screens = "&[" + ", ".join(rs(s) for s in as_list(a.get("screens"))) + "]"
    return (
        "    Block {\n"
        f"        id: {rs(a['id'])},\n"
        f"        name: {rs(a["name"])},\n"
        f"        action: {rs(sentence(a['action']))},\n"
        f"        standards: {lines(standard_lines(data, a))},\n"
        f"        implementation: {lines(implementation_lines(a, versions))},\n"
        f"        checked: {lines(checked_lines(a))},\n"
        f"        cross_check: {cc},\n"
        f"        independence: {lines(independence_lines(a))},\n"
        f"        code: {code_entries(a)},\n"
        f"        secret: {lines(secret_lines(a))},\n"
        f"        limits: {lines([('plain', sentence(t)) for t in a['limits']['lines']])},\n"
        f"        own_calls: {lines(own_lines(a))},\n"
        f"        screens: {screens},\n"
        f"        learn: {rs(learn)},\n"
        "    },\n"
    )


def learn_page_fn(data):
    """`learn_page`: the Learn page each block's `learn` names, as the apps hold it."""
    ids = []
    for a in data["action"]:
        i = a["learn"]
        if i != "none" and i not in ids:
            ids.append(i)
    arms = []
    for i in ids:
        if i.startswith("faraday:"):
            arms.append(f'        {rs(i)} => crate::page({rs(i[8:])}),')
        else:
            arms.append(f'        {rs(i)} => Some(&crate::pages::EN.{i}),')
    return (
        "/// The Learn page a block's `learn` names (a field of `pages::EN`, or\n"
        "/// `faraday:<id>` for one of Faraday's own). A lookup.\n"
        "pub fn learn_page(id: &str) -> Option<&'static crate::Page> {\n"
        "    match id {\n" + "\n".join(arms) + "\n        _ => None,\n    }\n}\n")


def generate(data, versions, seed, cases, facts, tail, constructions=""):
    """The whole of how.rs: the header, the areas, BLOCKS, `learn_page`, the
    CONSTRUCTIONS gen.py writes (docs/CRYPTO-LEARN.md §18), then `tail` (the lookups)."""
    facts, keys = facts
    areas = []
    for a in data["action"]:
        n = a["checked"].get("crosscheck")
        if n and n not in areas:
            areas.append(n)
    out = [HEADER]
    for n in areas:
        key = keys.get(n)
        if key is None:
            raise SystemExit(f"area {n}: no tools/crosscheck/area_{n}.py in the cross-check")
        if key not in cases:
            raise SystemExit(f"{STAMP}: no case count for area {key}")
        out.append("\n" + area_static(n, key, facts.get(key), seed, cases[key]))
    out.append("\n/// Every action's block, in the manifest's order.\n#[rustfmt::skip]\n"
               "pub static BLOCKS: &[Block] = &[\n")
    out += [block_text(data, a, versions) for a in data["action"]]
    out.append("];\n\n")
    out.append(learn_page_fn(data))
    out.append("\n")
    if constructions:
        out.append(constructions + "\n\n")
    out.append(tail)
    return "".join(out)


def how_text(root, data, constructions=""):
    """The text how.rs should have, with the CONSTRUCTIONS gen.py wrote."""
    root = pathlib.Path(root)
    old = (root / HOW).read_text()
    if MARKER not in old:
        raise SystemExit(f"{HOW}: the line `{MARKER}` is missing")
    tail = old[old.index(MARKER):]
    seed, cases = read_stamp(root)
    return generate(data, lock_versions(root), seed, cases, read_facts(root), tail,
                    constructions)


# ------------------------------------------------------------- the screens check

def code_map(root):
    """({Screen variant: file}, {file: [variants]}) from lib.rs's code map table."""
    text = (pathlib.Path(root) / "faraday/faraday-core/src/lib.rs").read_text()
    rows = re.findall(r"^//! \| `(\w+)` \| `([^`]+)` \|$", text, re.M)
    by_file = {}
    for screen, file in rows:
        by_file.setdefault(file, []).append(screen)
    return dict(rows), by_file


def module_screens(by_file, rel):
    """The screens a file of faraday-core serves: the file itself or its folder's screen.rs,
    or, for another file of an area's folder, the screens of that area."""
    parts = rel.split("/")
    keys = [rel]
    for i in range(len(parts) - 1, 0, -1):
        folder = "/".join(parts[:i])
        keys += [f"{folder}/screen.rs", f"{folder}/mod.rs", f"{folder}.rs"]
    out = []
    for k in keys:
        if k in by_file:
            out = by_file[k]
            break
    return out


def root_names(a):
    """(path tail, simple name, module) of each root of the action: `Mnemonic::from_entropy`,
    the module being the file's name (its folder's for a mod.rs)."""
    out = []
    for f in as_list(a.get("functions")):
        file, _, tail = f.partition("::")
        parts = pathlib.PurePosixPath(file)
        module = parts.parent.name if parts.stem == "mod" else parts.stem
        out.append((tail, tail.split("::")[-1], module))
    return out


# Method names the standard library and every type share: a call by one of these names
# says nothing about which type it is called on.
COMMON = {"parse", "hash", "split", "note", "new", "get", "from", "derive", "push", "len", "sign",
          "read", "write", "encode", "decode", "open", "check", "verify", "make", "load",
          "create", "text", "name", "key", "keys", "seed", "words", "find", "to_text", "recover",
          "combine", "start", "next", "step", "show", "reveal", "edit", "seal", "unlock",
          "address", "script", "scan", "hold"}


def names_type(text, crate, typ):
    """True where the text names `typ` from `crate`: a `use crate::..Type..;` line or a
    `crate::..::Type` path. A bare `Type` may be another crate's type of the same name."""
    t = re.escape(typ)
    c = re.escape(crate)
    return bool(re.search(rf"\buse\s+{c}::[^;]*\b{t}\b", text)
                or re.search(rf"\b{c}::(?:\w+::)*{t}\b", text))


def screens_check(root, data, detail=False):
    """[(action id, screen, file)] for each screen whose code, a file of faraday-core, calls
    an action's root and is missing from the action's `screens`.

    A call is a path call that ends in the root's last two segments, or a method call by
    the method's name for a root that is a method (`Type::name`) where the file names the
    type. The files read are those of faraday-core's `src/` (tests excluded)."""
    root = pathlib.Path(root)
    _, by_file = code_map(root)
    base = root / "faraday/faraday-core/src"
    if not base.is_dir() or not (base / "lib.rs").is_file():
        return []
    files = {}
    for p in sorted(base.rglob("*.rs")):
        rel = str(p.relative_to(base))
        text = re.sub(r"//[^\n]*", "", p.read_text())
        files[rel] = text
    found = set()
    for a in data["action"]:
        crates = [f.partition("::")[0].split("/")[1].replace("-", "_") if f.count("/") else ""
                  for f in as_list(a.get("functions"))]
        have = set(as_list(a.get("screens"))) | {n["screen"] for n in as_list(a.get("screens_not"))}
        for (tail, simple, module), crate in zip(root_names(a), crates):
            segs = tail.split("::")
            if len(segs) >= 2:
                typ = segs[-2]
                path_re = re.compile(rf"\b{re.escape(typ)}::{re.escape(simple)}\b")
                meth_re = re.compile(rf"\.{re.escape(simple)}\(")
            else:
                path_re = re.compile(rf"\b{re.escape(module)}::{re.escape(simple)}\b")
                meth_re = None
            for rel, text in files.items():
                if simple not in text:
                    continue
                m_ = path_re.search(text)
                if not m_ and meth_re and names_type(text, crate, typ) and simple not in COMMON \
                        and ("_" in simple or len(simple) >= 8):
                    m_ = meth_re.search(text)
                if not m_:
                    continue
                at = text.count("\n", 0, m_.start()) + 1
                snippet = text.split("\n")[at - 1].strip()[:100]
                for screen in module_screens(by_file, rel):
                    if screen not in have:
                        found.add((a["id"], screen, f"{rel}:{at}: {snippet}" if detail else rel))
    return sorted(found)


def cmd_check_screens(root):
    data = tomllib.loads((pathlib.Path(root) / "docs/crypto/actions.toml").read_text())
    found = screens_check(root, data, detail="--lines" in sys.argv)
    if not found:
        print("screens: every screen whose code calls an action's root is in its `screens`")
        return 0
    pairs = sorted({(a, s) for a, s, _ in found})
    for a, s in pairs:
        files = sorted({f for x, y, f in found if (x, y) == (a, s)})
        print(f"{a}: add {s} to `screens` (called in {', '.join(files)})")
    print(f"{len(pairs)} (action, screen) pairs to add")
    return 1


# -------------------------------------------------------------------- self-test

def self_test():
    failures = []

    def expect(cond, what):
        print(f"  {'ok  ' if cond else 'FAIL'} {what}")
        if not cond:
            failures.append(what)

    data = {"standard": {"BIP 39": {"name": "Mnemonic", "status": "Deployed", "source": "bips master"}}}
    a = {"id": "x", "name": "Make the words", "action": "Turns sixteen bytes of entropy into words, with a checksum.", "learn": "words",
         "screens": ["KeyGen"], "standards": ["BIP 39"], "code": ["core/f/src/a.rs::T::go"],
         "implementation": {"crate": "core/f", "libraries": ["k"], "adds": "Adds a thing"},
         "checked": {"tests": ["t.rs::a"], "not_crosschecked": "No second one.", "fuzz_none": "Fixed length."},
         "secrets": {"reveal": "none", "constant_time": "not stated by the library", "wiped": "Dropped"},
         "limits": {"lines": ["Only this"]}, "own": [{"text": "Refuses", "kind": "Conservative"}]}
    out = block_text(data, a, {"k": ["1.2.3"]})
    expect('name: "Make the words"' in out, "the name is the manifest's")
    expect('m("k 1.2.3")' in out, "a library's version is read from the lock")
    expect('w("not checked against vectors")' in out, "no vectors is a warning")
    expect('w("no fuzz target: Fixed length")' in out, "no fuzz target says why")
    expect('CrossCheck::Not("not cross-checked: No second one")' in out, "no area says why")
    expect('w("no decision")' in out and 'w("not stated by the library.")' in out, "no decision warns")
    expect('c("core/f/src/a.rs", "T::go")' in out, "code splits at the first ::")
    expect(prose("its files `x` are") == "Its files x are.", "prose capitalises a word, not a path")
    expect(prose("faraday_bip::bip39") == "faraday_bip::bip39.", "and leaves an identifier alone")
    clash = "use faraday_shell_api::Key;\nlet k = FileKind::Key;\n"
    expect(not names_type(clash, "faraday_pgp", "Key"), "another crate's Key is not faraday_pgp's")
    expect(names_type("use faraday_pgp::{Key, Other};", "faraday_pgp", "Key"), "a use line names the type")
    expect(names_type("let k = faraday_pgp::Key::new();", "faraday_pgp", "Key"), "a path names the type")
    if failures:
        print(f"{len(failures)} failed")
        return 1
    print("gen_how.py self-test passed")
    return 0


def main(argv):
    if argv[1:] == ["--self-test"]:
        return self_test()
